export function localeOf(lang: Lang): string {
  return lang === "hr" ? "hr-HR" : "de-DE";
}

/** Pfad in der jeweiligen Sprache ("/sport" → "/hr/sport"). */
export function href(lang: Lang, path: string): string {
  if (lang === "de") return path;
  if (path === "/") return "/hr";
  if (path.startsWith("/#")) return `/hr${path.slice(1)}`;
  return `/hr${path}`;
}

